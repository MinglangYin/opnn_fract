import matplotlib
import matplotlib.pyplot as plt
from mpl_toolkits.axes_grid1 import make_axes_locatable
matplotlib.use('Agg')

def plotField(damage_pred_print, damage_true_print, xDisp_pred_print, xDisp_true_print, yDisp_pred_print, yDisp_true_print, step, dump_train):
        print(f"printing step: {step+1}")
        fig = plt.figure(constrained_layout=False, figsize=(10, 10))
        gs = fig.add_gridspec(3, 3)
        plt.subplots_adjust(left=0.1,bottom=0.1, right=0.9, top=0.9, wspace=0.6, hspace=0.4)
        
        ax = fig.add_subplot(gs[0,0])        
        h = ax.imshow(damage_pred_print,origin='lower')
        ax.set_title('Testing case Phi (Pred): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)

        ax = fig.add_subplot(gs[1,0])
        h = ax.imshow(damage_true_print,origin='lower')
        ax.set_title('Testing case Phi (True): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)
        
        ax = fig.add_subplot(gs[2,0])
        h = ax.imshow(abs(damage_pred_print - damage_true_print),origin='lower')
        ax.set_title('Testing case Phi (Err): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)        
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)
        
        ax = fig.add_subplot(gs[0,1])
        h = ax.imshow(xDisp_pred_print,origin='lower')
        ax.set_title('Testing case X_disp (Pred): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)        
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)

        ax = fig.add_subplot(gs[1,1])
        h = ax.imshow(xDisp_true_print,origin='lower')
        ax.set_title('Testing case X_disp (True): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)        
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)
        
        ax = fig.add_subplot(gs[2,1])
        h = ax.imshow(abs(xDisp_pred_print - xDisp_true_print),origin='lower')
        ax.set_title('Testing case X_disp (Err): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)        
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)
        
        ax = fig.add_subplot(gs[0,2])
        h = ax.imshow(yDisp_pred_print, origin='lower')
        ax.set_title('Testing case Y_disp (Pred): ' + str(step+1))
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)        
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)

        ax = fig.add_subplot(gs[1,2])
        h = ax.imshow(yDisp_true_print,origin='lower')
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)
        ax.set_title('Testing case Y_disp (True): ' + str(step+1))
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)
        
        ax = fig.add_subplot(gs[2,2])
        h = ax.imshow(abs(yDisp_pred_print - yDisp_true_print),origin='lower')
        ax.axes.xaxis.set_visible(False)
        ax.axes.yaxis.set_visible(False)
        ax.set_title('Testing case Y_disp (Err): ' + str(step+1))
        # h.set_clim(vmin=0, vmax=1)
        divider = make_axes_locatable(ax)
        cax = divider.append_axes("right", size="5%", pad=0.05)
        fig.colorbar(h, ax=ax, cax=cax)

        fig.savefig(dump_train + '/step_' + str(step+1) + '.png')
        plt.close()
    